/**
 * One-off image optimiser (run by .github/workflows/optimize-images.yml).
 *
 * The Lovable CDN serves the original phone photos (up to 7 MB, 4032 px).
 * This fetches each one, fixes EXIF rotation and writes WebP versions at a few
 * widths to public/img/o/, plus src/data/optimizedImages.ts, which the <Photo>
 * component and the hero use to serve responsive, lightweight images.
 */
import fs from 'fs';
import path from 'path';
import sharp from 'sharp';
import { CDN_IMAGE_MAP } from '../src/data/cdnImageMap';

const ORIGIN = 'https://xtsy.one';
const OUT = 'public/img/o';
const WIDTHS = [640, 1280];
/** Landscape covers used full-bleed get an extra large size. */
const WIDE = new Set(['xtsy/Property Images 8.jpg', 'xtsy/Property Images 6.jpg', 'xtsy/TAB Bistro by XTSY 1.jpeg']);

const slug = (key: string) => key.toLowerCase().replace(/\.[a-z]+$/, '').replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

async function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const manifest: Record<string, { w: number; h: number; srcs: [number, string][] }> = {};
  let before = 0; let after = 0;
  for (const [key, p] of Object.entries(CDN_IMAGE_MAP)) {
    if (/logo/i.test(key)) continue;
    try {
      const res = await fetch(ORIGIN + p);
      if (!res.ok) { console.warn('skip', key, res.status); continue; }
      const buf = Buffer.from(await res.arrayBuffer());
      before += buf.length;
      const base = sharp(buf).rotate();
      const meta = await base.metadata();
      const rotated = (meta.orientation ?? 1) >= 5;
      const w0 = (rotated ? meta.height : meta.width) ?? 0;
      const h0 = (rotated ? meta.width : meta.height) ?? 0;
      const widths = [...WIDTHS, ...(WIDE.has(key) ? [1920] : [])].filter((w, i, a) => w < w0 || i === 0 || a[i - 1] < w0).map((w) => Math.min(w, w0));
      const srcs: [number, string][] = [];
      for (const w of [...new Set(widths)]) {
        const file = `${slug(key)}-${w}.webp`;
        const out = await sharp(buf).rotate().resize({ width: w, withoutEnlargement: true }).webp({ quality: 68, effort: 5 }).toBuffer();
        fs.writeFileSync(path.join(OUT, file), out);
        after += out.length;
        srcs.push([w, `/img/o/${file}`]);
      }
      manifest[p] = { w: w0, h: h0, srcs };
      console.log(key, `${Math.round(buf.length / 1024)} KB →`, srcs.map(([w]) => w).join('/'));
    } catch (e) {
      console.warn('failed', key, e);
    }
  }
  const ts = `// AUTO-GENERATED by scripts/optimize-images.ts — responsive WebP versions of the\n// Lovable CDN photos. Keys are the CDN paths from cdnImageMap.ts.\nexport const OPTIMIZED_IMAGES: Record<string, { w: number; h: number; srcs: [number, string][] }> = ${JSON.stringify(manifest, null, 1)};\n`;
  fs.writeFileSync('src/data/optimizedImages.ts', ts);
  console.log(`Originals ${Math.round(before / 1048576)} MB → WebP ${Math.round(after / 1048576)} MB (all sizes)`);
}

main().catch((e) => { console.error(e); process.exit(1); });
