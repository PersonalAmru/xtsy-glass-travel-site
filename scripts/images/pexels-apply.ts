/**
 * Step 2 of 2 (CI): download the reviewed picks (scripts/images/pexels-picks.json,
 * { targetKey: candidateNumber }) at full quality, write WebP versions to
 * public/img/px/, and generate src/data/pexelsPhotos.ts with photographer credits.
 * Uses the image CDN only (no API calls).
 */
import fs from 'fs';
import sharp from 'sharp';

type Cand = { n: number; id: number; alt: string; url: string; photographer: string; photographerUrl: string; src: string };
const cands: Record<string, Cand[]> = JSON.parse(fs.readFileSync('scripts/images/pexels-candidates.json', 'utf8'));
const picks: Record<string, number> = JSON.parse(fs.readFileSync('scripts/images/pexels-picks.json', 'utf8'));
const OUT = 'public/img/px';
const WIDTHS = [640, 1280];

async function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const used = new Set<number>();
  const manifest: Record<string, unknown> = {};
  for (const [key, n] of Object.entries(picks)) {
    const c = cands[key]?.find((x) => x.n === n);
    if (!c) { console.log(`::warning::${key}: candidate ${n} not found`); continue; }
    if (used.has(c.id)) { console.log(`::error::${key}: photo ${c.id} already used by another card`); process.exitCode = 1; continue; }
    used.add(c.id);
    const buf = Buffer.from(await (await fetch(`${c.src}?auto=compress&cs=tinysrgb&w=1600`)).arrayBuffer());
    const base = sharp(buf).rotate();
    const meta = await base.metadata();
    const srcs: [number, string][] = [];
    for (const w of WIDTHS) {
      const file = `${OUT}/${key}-${w}.webp`;
      await sharp(buf).rotate().resize({ width: w, withoutEnlargement: true }).webp({ quality: 74 }).toFile(file);
      srcs.push([w, `/img/px/${key}-${w}.webp`]);
    }
    const ratio = (meta.height ?? 1) / (meta.width ?? 1);
    manifest[key] = { w: 1280, h: Math.round(1280 * ratio), srcs, alt: c.alt, photographer: c.photographer, photographerUrl: c.photographerUrl, pexelsUrl: c.url, pexelsId: c.id };
    console.log(key, c.id, c.photographer);
  }
  const body = `// AUTO-GENERATED by scripts/images/pexels-apply.ts — reviewed Pexels photographs
// (free to use under the Pexels licence; photographers credited on the page).
export type PexelsPhoto = { w: number; h: number; srcs: [number, string][]; alt: string; photographer: string; photographerUrl: string; pexelsUrl: string; pexelsId: number };
export const PEXELS_PHOTOS: Record<string, PexelsPhoto> = ${JSON.stringify(manifest, null, 1)};
`;
  fs.writeFileSync('src/data/pexelsPhotos.ts', body);
  console.log(`::notice::Applied ${Object.keys(manifest).length} Pexels photos`);
}
main();
