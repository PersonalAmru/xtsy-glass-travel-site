/**
 * One-off (CI, when .github/fetch-fonts.flag exists): self-host the two brand
 * fonts so they can be preloaded from our own origin — no third-party CSS hop,
 * and the headline font arrives before first paint (less layout shift).
 * Writes public/fonts/*.woff2 and public/fonts/fonts.css (latin + latin-ext).
 */
import fs from 'fs';

const CSS_URL = 'https://fonts.googleapis.com/css2?family=Staatliches&family=Manrope:wght@400..800&display=swap';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36';

async function main() {
  fs.mkdirSync('public/fonts', { recursive: true });
  const css = await (await fetch(CSS_URL, { headers: { 'user-agent': UA } })).text();
  const blocks = css.split('/*').slice(1).map((b) => '/*' + b);
  let out = '/* Self-hosted from Google Fonts (OFL). Generated by scripts/fetch-fonts.ts */\n';
  for (const block of blocks) {
    const subset = /\/\*\s*([a-z-]+)\s*\*\//.exec(block)?.[1];
    if (subset !== 'latin' && subset !== 'latin-ext') continue;
    const family = /font-family:\s*'([^']+)'/.exec(block)?.[1] ?? 'font';
    const url = /url\((https:[^)]+\.woff2)\)/.exec(block)?.[1];
    if (!url) continue;
    const file = `${family.toLowerCase().replace(/\s+/g, '-')}-${subset}.woff2`;
    fs.writeFileSync(`public/fonts/${file}`, Buffer.from(await (await fetch(url)).arrayBuffer()));
    out += block.replace(url, `/fonts/${file}`).trim() + '\n';
    console.log(family, subset, file);
  }
  fs.writeFileSync('public/fonts/fonts.css', out);
}
main().catch((e) => { console.error(e); process.exit(1); });
