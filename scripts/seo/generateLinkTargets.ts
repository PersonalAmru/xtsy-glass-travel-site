/**
 * Writes src/data/linkTargets.ts: retired slugs (no live page, no route) → the live page
 * they redirect to. The shared <Link> uses it so internal links never point at a
 * redirect or a 404. Run after editing RECOVERY_REDIRECTS:  bun scripts/seo/generateLinkTargets.ts
 */
import fs from 'fs';
import { RECOVERY_REDIRECTS } from '../../src/data/seoAffectedSlugs';
import { programmaticModel, isThinSEOPage } from '../../src/lib/seo/programmaticSeo';

const tree = fs.readFileSync('src/routeTree.gen.ts', 'utf8');
const routes = new Set([...tree.matchAll(/fullPath: '([^']+)'/g)].map((m) => m[1]));
const live = (slug: string) => { const m = programmaticModel(slug); return (m && !isThinSEOPage(m.page)) || routes.has('/' + slug); };
const out: Record<string, string> = {};
for (const [k, v] of Object.entries(RECOVERY_REDIRECTS)) {
  if (live(k)) continue;
  if (!live(v.replace(/^\//, '').split(/[?#]/)[0]) && !routes.has(v)) throw new Error(`Redirect target is not live: ${k} → ${v}`);
  out[k] = v;
}
const body = Object.entries(out).sort().map(([k, v]) => `  '${k}': '${v}',`).join('\n');
fs.writeFileSync('src/data/linkTargets.ts', `// Generated by scripts/seo/generateLinkTargets.ts — do not edit by hand.
/** Retired slug → live page. Used by <Link> so internal links skip redirects and 404s. */
export const LINK_TARGETS: Readonly<Record<string, string>> = {
${body}
};

/** Rewrites an internal href that points at a retired slug to its live page. */
export function resolveLinkTarget(to: string): string {
  const m = /^\\/([^/?#]+)\\/?([?#].*)?$/.exec(to);
  const target = m ? LINK_TARGETS[m[1]] : undefined;
  return target ? target + (m?.[2] && !target.includes(m[2][0]) ? m[2] : '') : to;
}
`);
console.log(`${Object.keys(out).length} retired slugs → src/data/linkTargets.ts`);
